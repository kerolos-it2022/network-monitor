// ui-text.service.js — نصوص **يراها المستخدم في الواجهة** بلغتين، تتبع إعداد لغة الواجهة.
// ═══════════════════════════════════════════════════════════════════════════
// تختلف عن message-i18n.service.js اختلافًا مقصودًا:
//   • message-i18n → نصوص **الرسائل المُرسَلة** (تلجرام/واتساب/…) وتتبع إعداد لغة **الإشعارات**.
//   • هذا الملف  → نصوص يقرأها المستخدم **داخل الواجهة**: رسائل أخطاء الـAPI، أسباب تخطّي القنوات،
//     نصوص التقدّم (المسح/التحديث)، أي رسالة يرجعها الخادم ويُعرضها المتصفح كما هي.
//     وتتبع إعداد لغة **الواجهة** (app_settings.ui_language) لأنه هو ما يُعرض على الشاشة.
//
// الاستعمال:  error: uiText('الجهاز غير موجود', 'Device not found')
// والعربي يبقى **حرفيًّا** كما كان في الكود (هو المخرَج في وضع العربية، وعليه تعتمد الاختبارات القائمة).
//
// ملاحظة للفرونت: المواضع التي يقارن فيها المتصفح **نصّ** الخطأ بالحرف (‎.includes('…')‎) يجب أن
// تُقارَن بكود ثابت بدلًا منه — فيُرسَل مع الخطأ حقل `code` (انظر routes) ويُقارن المتصفح به.
'use strict';
const uiLang = require('./ui-language.service');

/** uiText(ar, en) — النصّ بلغة الواجهة الحالية (الافتراضي إنجليزي). */
function uiText(ar, en) {
  return uiLang.getLang() === 'ar' ? ar : en;
}

/** uiLangCode() — اللغة الحالية للواجهة ('ar' | 'en') — للاستعمال عند الحاجة لفرع كامل. */
function uiLangCode() { return uiLang.getLang(); }

module.exports = { uiText, uiLangCode };
